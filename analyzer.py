DASHES = dict.fromkeys(map(ord, "‐‑‒–—―−"), "-")
SPACES = dict.fromkeys(map(ord, "       "), " ")


def normalize(text):
    """Приводит текст к единому виду перед разбором."""
    t = text.lower().translate(DASHES).translate(SPACES)
    t = t.replace("ё", "е")          # «вёрстка» и «верстка» — одно слово
    return re.sub(r"[ \t]+", " ", t)


# Списки из config.py прогоняем через ту же нормализацию — иначе «вёрстка»
# из конфига не совпадёт с «верстка» в нормализованном тексте.
_STOP = [normalize(w) for w in config.STOP_WORDS]
_STOP_ROLES = [normalize(w) for w in config.STOP_ROLES]
_EXCHANGE = [normalize(w) for w in config.EXCHANGE_MARKERS]
_MY_CITIES = [normalize(w) for w in config.MY_CITIES]
_VACANCY = [normalize(w) for w in config.VACANCY_MARKERS]
_CONTENT = [normalize(w) for w in config.CONTENT_MARKERS]
_KEYWORDS = {
    cat: {"strong": [normalize(w) for w in groups["strong"]],
          "weak": [normalize(w) for w in groups["weak"]]}
    for cat, groups in config.KEYWORDS.items()
}


def analyze(text, is_order=False, is_part=False):
    """
    Главная функция. Принимает текст вакансии, возвращает разбор.

    is_order=True — текст пришёл с биржи заказов (FL.ru). Там всё по
    определению работа, поэтому проверку «а вакансия ли это вообще»
    пропускаем: заголовок «Собрать сайт на Tilda» её бы не прошёл.

    is_part=True — это кусок дайджеста, вырезанный из общего поста.
    Такие куски короткие всегда, и штрафовать их за краткость нельзя:
    в дайджесте вакансию описывают двумя строками, это норма жанра,
    а не признак развода.

    Возвращает словарь:
      relevant  — подходит ли по профилю (bool)
      reason    — если не подходит, почему
      verdict   — "ok" | "suspicious" | "scam"
      trust     — числовая оценка доверия
      why       — список причин для вердикта (что показать в сообщении)
      category  — design / frontend / project
      salary    — (мин, макс, как_написано)
      is_project— разовый заказ, а не наём (bool)
    """
    t = normalize(text)
    out = {
        "relevant": False, "reason": "", "verdict": "ok", "trust": 0,
        "why": [], "category": None, "salary": (None, None, None),
        "is_project": False, "is_senior": False,
    }

    # --- 1. Это резюме, а не вакансия? ---
    if _find(RESUME_MARKERS, t):
        out["reason"] = "это резюме соискателя, а не вакансия"
        return out

    # --- 2. Стоп-слова, действующие по всему тексту ---
    for w in _STOP:
        if w in t:
            out["reason"] = f"стоп-слово: «{w}»"
            return out

    # --- 2.2. Перепечатка с биржи ---
    if config.SKIP_EXCHANGE_REPOSTS:
        for w in _EXCHANGE:
            if w in t:
                out["reason"] = f"перепечатка с биржи: «{w}»"
                return out

    # --- 2.5. Чужая профессия — смотрим только заголовок ---
    # Должность объявляют в первых строках. Ниже по тексту те же слова
    # встречаются как перечисление задач или состава команды: у веб-дизайнера
    # в требованиях бывают «нейросети», а в описании студии — «фотограф».
    # По ним вакансию отсекать нельзя.
    head = t[:config.TITLE_LENGTH]
    for w in _STOP_ROLES:
        if w in head:
            out["reason"] = f"другая профессия: «{w}»"
            return out

    # --- 3. Это вообще вакансия, а не статья и не мем? ---
    if not is_order and not any(w in t for w in _VACANCY):
        out["reason"] = "не похоже на вакансию — просто пост"
        return out

    # --- 3.5. Контент и реклама под видом вакансии ---
    # «Разобрал 4 ошибки в видео», «забирайте гайд в моём боте» — такие посты
    # проходят проверку выше, потому что содержат и «вакансию», и «портфолио»,
    # и «требования». Но зовут они смотреть и подписываться, а не работать.
    content_hits = [w for w in _CONTENT if w in t]
    if content_hits and not is_order:
        out["reason"] = f"реклама или статья, а не вакансия: «{content_hits[0]}»"
        return out

    # --- 4. Профиль: наше или нет ---
    # Считаем по тексту БЕЗ хештегов. Каналы клеят один и тот же набор тегов
    # на все посты подряд: у @runello_rus_webdesign «#webdesign» стоит даже
    # на вакансии разработчика C++. По тегам судить нельзя, только по тексту.
    body = re.sub(r"#\w+", " ", t)

    scored = []
    has_strong = False
    for cat, groups in _KEYWORDS.items():
        strong = [w for w in groups["strong"] if w in body]
        weak = [w for w in groups["weak"] if w in body]
        score = len(strong) * 3 + len(weak)
        if strong:
            has_strong = True
        if score:
            scored.append([cat, score, (strong or weak)[0]])

    # Шаблоны разовых заказов идут в ту же копилку, но по регуляркам
    project_hits = [p for p in PROJECT_PATTERNS if re.search(p, body, re.I)]
    if project_hits:
        bonus = 3 * len(project_hits)
        found = next((s for s in scored if s[0] == "project"), None)
        if found:
            found[1] += bonus
        else:
            m = re.search(project_hits[0], body, re.I)
            scored.append(["project", bonus, m.group(0)[:40] if m else "заказ"])

    # Формат оплаты добавляет вес, но только если работа и так наша.
    # Без этого условия «сдельная оплата» в вакансии оператора станции
    # превращала её в «проектную работу по вёрстке».
    if scored and any(re.search(p, body, re.I) for p in PROJECT_FORMAT):
        found = next((s for s in scored if s[0] == "project"), None)
        if found:
            found[1] += 1

    if not scored:
        out["reason"] = "не про веб-дизайн, вёрстку или сайты"
        return out

    # Одних слабых слов мало, сколько бы их ни набралось. «Макет», «прототип»
    # и «Figma» вместе дают проходной балл, но встречаются и в вакансии
    # 3D-моделлера — там тоже макеты и прототипы. Нужно хотя бы одно точное
    # попадание: «веб-дизайнер», «верстальщик» или шаблон разового заказа.
    if not has_strong and not project_hits:
        out["reason"] = ("только общие слова про дизайн, "
                         "нет прямого указания на веб / вёрстку")
        return out

    # Обычная удалёнка живёт по своим правилам: она нужна только если
    # включена флагом и только если работа действительно удалённая.
    # «Менеджер по продажам» без слова «удалённо» — это офис в чужом городе.
    if not config.SEND_OTHER_REMOTE:
        scored = [s for s in scored if s[0] != "remote"]
    elif any(s[0] == "remote" for s in scored) and not _find(REMOTE_MARKERS, body):
        scored = [s for s in scored if s[0] != "remote"]

    if not scored:
        out["reason"] = "не про веб-дизайн, вёрстку или сайты"
        return out

    scored.sort(key=lambda x: x[1], reverse=True)
    best_cat, best_score, best_word = scored[0]

    if best_score < config.RELEVANCE_MIN:
        out["reason"] = (f"слабое совпадение по профилю "
                         f"(«{best_word}», {best_score} балла из {config.RELEVANCE_MIN})")
        return out

    out["relevant"] = True
    out["category"] = best_cat
    out["relevance"] = best_score
    out["matched_word"] = best_word
    out["is_project"] = any(c == "project" and s >= config.RELEVANCE_MIN
                            for c, s, _ in scored)

    # --- 5. Уровень ---
    # Заголовок, а не весь текст: «senior» в перечислении команды и
    # «отчитываешься арт-директору» — это не про требуемый уровень.
    if _find(SENIOR_MARKERS, head):
        out["is_senior"] = True
        if config.SKIP_SENIOR:
            out["relevant"] = False
            out["reason"] = "позиция для сеньора / лида"
            return out

    exp = required_experience(text)
    out["experience"] = exp
    if exp is not None and exp > config.MAX_EXPERIENCE_YEARS:
        out["relevant"] = False
        out["reason"] = (f"требуют опыт от {exp:g} лет "
                         f"(потолок {config.MAX_EXPERIENCE_YEARS:g})")
        return out

    # --- 5.5. Формат работы ---
    # Гибрид и офис не нужны, кроме своего города: ездить в Москву
    # два раза в неделю невозможно, а в Новосибирск — вполне.
    # Слово «удалённо» перевешивает: «удалённо или гибрид» — это удалёнка.
    if config.SKIP_OFFICE and not _find(REMOTE_MARKERS, t):
        office = _find(OFFICE_MARKERS, t)
        if office:
            if not any(city in t for city in _MY_CITIES):
                m = re.search(office[0], t, re.I)
                out["relevant"] = False
                out["reason"] = (f"офис или гибрид не в твоём городе: "
                                 f"«{m.group(0) if m else 'офис'}»")
                return out
            out["is_office_local"] = True

    # --- 6. Зарплата ---
    out["salary"] = extract_salary(text)

    # --- 7. Вердикт: честная или развод ---
    red_score, red_why = 0, []
    for pattern, weight, explain in RED_FLAGS:
        if re.search(pattern, t, re.I):
            red_score += weight
            red_why.append(explain)

    green_score, green_why = 0, []
    for pattern, weight, explain in GREEN_FLAGS:
        if re.search(pattern, t, re.I):
            green_score += weight
            green_why.append(explain)

    # Очень короткий текст — подозрительно само по себе:
    # нормальная вакансия не описывается двумя строчками.
    # Кроме случая, когда это вырезка из дайджеста — там иначе не пишут.
    if not is_part and len(text.strip()) < 180:
        red_score += 1
        red_why.append("слишком короткое описание, почти нет конкретики")

    out["trust"] = green_score - red_score
    out["green_why"] = green_why

    if red_score >= 5:
        out["verdict"] = "scam"
    elif red_score >= 2 or (red_score and green_score < 2):
        out["verdict"] = "suspicious"
    else:
        out["verdict"] = "ok"

    out["why"] = red_why
    return out


# Название должности в начале строки — так выглядит пункт дайджеста
# («1. Графический дизайнер в ГК Optimum System»), в отличие от пункта
# списка обязанностей, где стоит глагол («1. Рисовать макеты»).
ROLE_IN_LINE = re.compile(
    r"дизайнер|designer|разработчик|developer|верстальщик|менеджер|"
    r"маркетолог|копирайтер|редактор|аналитик|ассистент|специалист|"
    r"инженер|тестировщик|администратор|оператор|продакт|проджект",
    re.I)


def split_digest(text):
    """
    Разбивает сборный пост на отдельные вакансии.

    Каналы часто публикуют дайджест: «Требуются специалисты: 1. Дизайнер
    упаковок… 2. Вебдизайнер на Tilda… 8. Журналист…». Для разбора это
    беда — одно стоп-слово из восьмого пункта отсекало весь пост вместе
    с подходящей вакансией во втором.

    Возвращает список кусков или пустой список, если пост обычный.
    Обязанности, перечисленные списком внутри одной вакансии, не разбиваем:
    признак дайджеста — у каждого пункта свой контакт или своя профессия.
    """
    if not text or len(text) < 150:
        return []

    # Режем по началу строки вида «1.», «2)», «3 -»
    parts = re.split(r"\n(?=\s*\d{1,2}\s*[\.\)\-–]\s*\S)", text)
    parts = [p.strip() for p in parts if len(p.strip()) >= 50]

    # Если нумерации нет, пробуем буллеты. Каналы публикуют «пакеты
    # вакансий» на полсотни пунктов через «•», и без этого такая простыня
    # уходила в бот целиком — вместе с чужими вакансиями и враньём
    # в зарплате, собранным со всего поста разом.
    if len(parts) < 2:
        bullets = re.split(r"\n(?=\s*[•·▪‣●○]\s*\S)", text)
        bullets = [b.strip() for b in bullets if len(b.strip()) >= 30]
        # Буллетами оформляют и список обязанностей внутри одной вакансии
        # («• Отвечать за пользовательский опыт», «• Анализировать
        # результаты»). Разрезать такое нельзя — в бот уйдёт огрызок
        # вместо вакансии.
        #
        # Отличаем по двум признакам: должность стоит в самом начале
        # пункта, и таких пунктов большинство. У списка обязанностей
        # пункты начинаются с глагола, и должность там если и мелькнёт,
        # то в одном-двух из десяти.
        if len(bullets) >= 3:
            with_role = sum(1 for b in bullets
                            if ROLE_IN_LINE.search(b.split("\n")[0][:45]))
            if with_role >= 3 and with_role >= len(bullets) * 0.5:
                parts = bullets

    # Третий формат: вакансии разделены хештегом-профессией на своей строке.
    #   #дизайнеродежды
    #   Бренд одежды ищет дизайнера…
    #   ➡️ @nuhbala_sw
    if len(parts) < 2:
        tagged = re.split(r"\n(?=\s*#[\w]+\s*\n)", text)
        tagged = [x.strip() for x in tagged if len(x.strip()) >= 30]
        if len(tagged) >= 3:
            parts = tagged

    if len(parts) < 2:
        return []

    # Проверяем, что это действительно разные вакансии, а не список задач.
    # Признак дайджеста — у пунктов есть свои контакты, свои хештеги-профессии
    # или названия должностей: «1. Графический дизайнер в Optimum System».
    # Список обязанностей внутри одной вакансии выглядит иначе: там глаголы
    # («рисовать макеты», «верстать страницы»), а не должности.
    with_contact = sum(1 for p in parts if re.search(r"@\w{4,}", p))
    with_tag = sum(1 for p in parts
                   if re.search(r"#\w*(дизайн|разраб|верстал|менеджер|маркет|"
                                r"копирайт|автор|редактор|смм|smm|таргет)", p, re.I))
    with_role = sum(1 for p in parts if ROLE_IN_LINE.search(p.split("\n")[0]))

    if with_contact < 2 and with_tag < 2 and with_role < 3:
        return []

    return parts


def extract_all(text, is_order=False):
    """
    Достаёт из поста все подходящие вакансии.

    Обычный пост даёт одну запись. Дайджест может дать несколько: в одном
    сообщении встречаются и «Вебдизайнер на Tilda», и «Верстальщик» — обе
    нужны, поэтому возвращаем список, а не первое попавшееся.

    Каждый элемент — пара (разбор, текст для отправки).

    Дайджест разбираем по частям всегда, даже если он проходит целиком:
    пост «Вакансии на сегодня: 1. Графический дизайнер… 7. Веб-дизайнер…»
    формально подходит из-за седьмого пункта, но присылать простыню
    из восьми чужих вакансий вместо одной нужной незачем.
    """
    parts = split_digest(text)
    if parts:
        found = []
        for part in parts:
            sub = analyze(part, is_order, is_part=True)
            if sub["relevant"]:
                found.append((sub, part))
        if found:
            return found

        # Ни один пункт не подошёл — значит слать нечего. Раньше в этом
        # случае разбирался весь пост целиком, и список «Вакансии на
        # сегодня: 1. Графический дизайнер… 5. Дизайнер продукта…»
        # уходил простынёй: формально он подходит, ведь слово «дизайнер»
        # в нём есть. Но ни одной нужной вакансии там нет.
        return [({"relevant": False, "reason": "в пакете нет подходящих вакансий",
                  "verdict": "ok", "category": None, "is_project": False,
                  "salary": (None, None, None), "why": [], "trust": 0},
                 text)]

    analysis = analyze(text, is_order)
    return [(analysis, text)]


def analyze_with_digest(text, is_order=False):
    """Короткая форма extract_all — когда нужна только первая находка."""
    return extract_all(text, is_order)[0]


def salary_ok(salary, is_project=False, category=None):
    """
    Проходит ли вакансия по деньгам.

    Порогов три, и это не прихоть: 15 000 ₽ за лендинг — нормальная цена
    проекта, 40 000 ₽ — нормальная зарплата оператора чата, но для
    веб-дизайнера в штат и то и другое мало. Один порог на всех отсекал бы
    либо половину заказов, либо всю обычную удалёнку.
    """
    lo, hi, raw = salary
    if lo is None:
        return config.SEND_WITHOUT_SALARY
    if is_project:
        threshold = config.MIN_PROJECT_BUDGET
    elif category == "remote":
        threshold = config.MIN_SALARY_OTHER
    else:
        threshold = config.MIN_SALARY
    return max(lo, hi or lo) >= threshold
