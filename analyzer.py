# Числа считаем только рядом со словом «опыт» или «стаж». Без этого
# условия фраза «компания работает на рынке более 10 лет», которая есть
# в половине вакансий, читалась бы как требование десятилетнего стажа.
EXP_ANCHOR = re.compile(r"опыт\w*|стаж\w*", re.I)

EXP_PATTERNS = [
    r"от\s*(\d+)\s*(?:-?х)?\s*(?:года|лет|год)",       # от 3 лет
    r"(\d+)\s*\+\s*(?:года|лет|год)",                   # 3+ года
    r"(\d+)\s*[-–—]\s*\d+\s*(?:года|лет)",              # 1-3 года → 1
    r"(?:не\s*менее|минимум|более|свыше)\s*(\d+)\s*(?:года|лет|год)",
    r"(\d+)\s*(?:года|лет|год)\s*(?:коммерческ\w*\s*)?(?:опыт|стаж)",
]

EXP_WORD_PATTERNS = [
    r"от\s*(\w+)\s*(?:года|лет)",
    r"(?:не\s*менее|минимум|более|свыше)\s*(\w+)\s*(?:года|лет)",
]


def required_experience(text):
    """
    Сколько лет опыта требует вакансия. Возвращает число или None.

    Берём минимальную границу: «от 1 года до 3 лет» — это 1, туда с годом
    опыта возьмут. А «от 3 лет» — это 3, и такие отсекаем.

    Ищем не по всему тексту, а в окне вокруг слов «опыт» и «стаж»:
    иначе под требование попадает возраст компании и срок работы на рынке.
    """
    t = normalize(text)
    years = []

    for anchor in EXP_ANCHOR.finditer(t):
        # окно: немного до слова «опыт» и заметно после
        window = t[max(0, anchor.start() - 40):anchor.end() + 60]

        for pattern in EXP_PATTERNS:
            for m in re.finditer(pattern, window, re.I):
                try:
                    n = int(m.group(1))
                except (ValueError, IndexError):
                    continue
                if 0 < n <= 20:
                    years.append(n)

        for pattern in EXP_WORD_PATTERNS:
            for m in re.finditer(pattern, window, re.I):
                word = m.group(1).lower()
                if word in WORD_YEARS:
                    years.append(WORD_YEARS[word])

    return min(years) if years else None


