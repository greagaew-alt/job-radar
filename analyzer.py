# «150 000», «150к», «от 100 000 до 150 000», «100-150к», «$1500»
#
# Порядок важен: сначала диапазоны, потом одиночные суммы. И везде стоит
# граница слова \b — без неё шаблон «70-120к» цеплялся к хвостам чисел:
# в строке «70 000 – 120 000 ₽» он находил «000 – 120» и умножал на тысячу,
# из-за чего нижняя граница вилки терялась, а зарплатой считалось 120 000.
SALARY_PATTERNS = [
    # от X до Y
    (r"от\s*(\d[\d\s]{2,8})\s*(?:руб|₽|р\.|тыс|к\b|k\b)?\s*до\s*(\d[\d\s]{2,8})", "range"),
    (r"(\d[\d\s]{4,8})\s*[-–—]\s*(\d[\d\s]{4,8})\s*(?:руб|₽|р\.)", "range"),
    # X - Y к/тыс
    (r"\b(\d{2,3})\s*[-–—]\s*(\d{2,3})\s*(?:к\b|k\b|тыс)", "range_k"),
    # от X
    (r"от\s*(\d[\d\s]{4,8})\s*(?:руб|₽|р\.)", "from"),
    (r"от\s*\b(\d{2,3})\s*(?:к\b|k\b|тыс)", "from_k"),
    # просто сумма
    (r"(\d[\d\s]{4,8})\s*(?:руб|₽|р\.)", "exact"),
    (r"\b(\d{2,3})\s*(?:к\b|k\b)", "exact_k"),
    # зП: 120000
    (r"(?:з/?п|зарплат\w*|оклад|вилка|бюджет)\D{0,12}(\d[\d\s]{4,8})", "exact"),
    # Валюта — в самом конце. Рублёвая зарплата всегда важнее: в тексте
    # вакансии «50 000 ₽» может попасться «$2000» из описания проектов,
    # и, стой этот шаблон выше, зарплатой стало бы 180 000 ₽.
    (r"[$€]\s*(\d[\d\s]{2,6})\s*[-–—]\s*[$€]?\s*(\d[\d\s]{2,6})", "range_cur"),
    (r"[$€]\s*(\d[\d\s]{2,6})", "exact_cur"),
]

CURRENCY_MULT = {"$": 90, "€": 100, "usd": 90, "eur": 100}


def extract_salary(text):
    """Достаёт зарплату из текста. Возвращает (мин, макс, как_было_написано)."""
    t = normalize(text)

    for pattern, kind in SALARY_PATTERNS:
        m = re.search(pattern, t)
        if not m:
            continue

        # Валюту ищем рядом с самим числом, а не по всему посту. Раньше
        # хватало одного «$» где угодно в тексте, чтобы каждая сумма
        # умножилась на 90: из «50 000 ₽» получалось «4 500 000 ₽».
        near = t[max(0, m.start() - 15):m.end() + 15]
        mult = 1
        for sign, rate in CURRENCY_MULT.items():
            if sign in near:
                mult = rate
                break
        try:
            nums = [int(g.replace(" ", "").replace(" ", ""))
                    for g in m.groups() if g]
        except ValueError:
            continue
        if not nums:
            continue

        if kind.endswith("_k"):
            nums = [n * 1000 for n in nums]
        # Шаблоны с валютой в записи ($1500) переводим по курсу всегда,
        # остальные — только если знак валюты стоит рядом с числом
        if kind.endswith("_cur"):
            rate = next((v for k, v in CURRENCY_MULT.items() if k in m.group(0)), 90)
            nums = [n * rate for n in nums]
        else:
            nums = [n * mult for n in nums]

        # отсекаем мусор: 3 рубля или 50 миллионов — это не зарплата
        nums = [n for n in nums if 10_000 <= n <= 5_000_000]
        if not nums:
            continue

        raw = m.group(0).strip()
        if kind.startswith("range"):
            return min(nums), max(nums), raw
        if kind.startswith("from"):
            return nums[0], None, raw
        return nums[0], nums[0], raw

    return None, None, None


def _find(patterns, text):
    """Ищет любое из выражений в тексте."""
    return [p for p in patterns if re.search(p, text, re.I)]


